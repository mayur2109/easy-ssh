pub const INCLUDE_LINE: &str = "Include ~/.ssh/easy-ssh.conf";
const INCLUDE_MARKER: &str = "# easy-ssh managed include";
const HOOK_START: &str = "# >>> easy-ssh shell hook >>>";
const HOOK_END: &str = "# <<< easy-ssh shell hook <<<";

#[derive(Debug, Clone, Copy, PartialEq, Eq, ValueEnum)]
pub enum Shell {
    Bash,
    Zsh,
}

impl Shell {
    fn startup_file(self, paths: &AppPaths) -> &Path {
        match self {
            Self::Bash => &paths.bashrc,
            Self::Zsh => &paths.zshrc,
        }
    }
}

pub fn selected_shells(explicit: &[Shell]) -> Result<Vec<Shell>> {
    resolve_shells(explicit, env::var_os("SHELL").as_deref())
}

fn resolve_shells(explicit: &[Shell], login_shell: Option<&OsStr>) -> Result<Vec<Shell>> {
    if !explicit.is_empty() {
        let mut selected = Vec::new();
        for shell in explicit {
            if !selected.contains(shell) {
                selected.push(*shell);
            }
        }
        return Ok(selected);
    }

    let login_shell = login_shell
        .map(Path::new)
        .and_then(Path::file_name)
        .and_then(OsStr::to_str)
        .unwrap_or("");
    match login_shell {
        "bash" => Ok(vec![Shell::Bash]),
        "zsh" => Ok(vec![Shell::Zsh]),
        _ => anyhow::bail!(
            "could not detect a supported shell from $SHELL; use --shell bash or --shell zsh"
        ),
    }
}

pub fn generated_config(file: &ProjectFile) -> String {
    let mut output =
        String::from("# Generated by easy-ssh. Edit projects with `easy-ssh`, not this file.\n\n");
    for project in &file.projects {
        if let Connection::NewHost {
            host,
            user,
            port,
            identity_file,
        } = &project.connection
        {
            output.push_str(&format!("Host {}\n", project.name));
            output.push_str(&format!("    HostName {}\n", quote_config(host)));
            if let Some(user) = user {
                output.push_str(&format!("    User {}\n", quote_config(user)));
            }
            if let Some(port) = port {
                output.push_str(&format!("    Port {port}\n"));
            }
            if let Some(identity_file) = identity_file {
                output.push_str(&format!(
                    "    IdentityFile {}\n",
                    quote_config(&identity_file.to_string_lossy())
                ));
            }
            output.push_str("    ServerAliveInterval 30\n");
            output.push_str("    ServerAliveCountMax 3\n");
            output.push('\n');
        }
    }
    output
}

pub fn sync_generated_config(paths: &AppPaths, file: &ProjectFile) -> Result<()> {
    fs::create_dir_all(&paths.ssh_dir)?;
    set_mode(&paths.ssh_dir, 0o700)?;
    atomic_write(
        &paths.managed_ssh_config,
        generated_config(file).as_bytes(),
        0o600,
    )
}

pub fn validate_connection_name(paths: &AppPaths, project: &Project) -> Result<()> {
    if matches!(project.connection, Connection::NewHost { .. })
        && discover_aliases(paths)
            .iter()
            .any(|alias| alias == &project.name)
    {
        anyhow::bail!(
            "SSH alias {:?} already exists; use an existing-alias project instead of replacing it",
            project.name
        );
    }
    Ok(())
}

pub fn install(paths: &AppPaths, file: &ProjectFile, shells: &[Shell]) -> Result<Vec<String>> {
    fs::create_dir_all(&paths.config_dir)?;
    fs::create_dir_all(&paths.ssh_dir)?;
    set_mode(&paths.ssh_dir, 0o700)?;

    let mut changes = Vec::new();
    if ensure_include(paths)? {
        changes.push(format!("updated {}", paths.ssh_config.display()));
    }
    for shell in shells {
        let startup_file = shell.startup_file(paths);
        if ensure_shell_hook(startup_file, *shell)? {
            changes.push(format!("updated {}", startup_file.display()));
        }
    }
    sync_generated_config(paths, file)?;
    changes.push(format!("generated {}", paths.managed_ssh_config.display()));
    Ok(changes)
}

fn ensure_include(paths: &AppPaths) -> Result<bool> {
    let old = read_or_empty(&paths.ssh_config)?;
    if old.lines().any(|line| line.trim() == INCLUDE_LINE) {
        return Ok(false);
    }
    backup_once(&paths.ssh_config)?;
    let mut new = format!("{INCLUDE_MARKER}\n{INCLUDE_LINE}\n");
    if !old.is_empty() {
        new.push('\n');
        new.push_str(&old);
        if !old.ends_with('\n') {
            new.push('\n');
        }
    }
    atomic_write(&paths.ssh_config, new.as_bytes(), 0o600)?;
    Ok(true)
}

fn ensure_shell_hook(startup_file: &Path, shell: Shell) -> Result<bool> {
    let old = read_or_empty(startup_file)?;
    let hook = shell_hook(shell);
    if old.contains(hook) {
        return Ok(false);
    }
    backup_once(startup_file)?;
    if let (Some(start), Some(end)) = (old.find(HOOK_START), old.find(HOOK_END)) {
        let end = end + HOOK_END.len();
        let new = format!("{}{}{}", &old[..start], hook, &old[end..]);
        atomic_write(startup_file, new.as_bytes(), 0o600)?;
        return Ok(true);
    }
    let separator = if old.is_empty() || old.ends_with('\n') {
        ""
    } else {
        "\n"
    };
    let new = format!("{old}{separator}\n{hook}\n");
    atomic_write(startup_file, new.as_bytes(), 0o600)?;
    Ok(true)
}

pub fn shell_hook(shell: Shell) -> &'static str {
    match shell {
        Shell::Bash => BASH_SHELL_HOOK,
        Shell::Zsh => ZSH_SHELL_HOOK,
    }
}

const BASH_SHELL_HOOK: &str = r#"# >>> easy-ssh shell hook >>>
ssh() {
    if [ "$#" -eq 1 ] && command easy-ssh __is-project -- "$1"; then
        command easy-ssh connect -- "$1"
    else
        command ssh "$@"
    fi
}
# <<< easy-ssh shell hook <<<

_easy_ssh_complete_project() {
    COMPREPLY=( $(compgen -W "$(command easy-ssh __complete-projects)" -- "$1") )
}

_easy_ssh() {
    local current="${COMP_WORDS[COMP_CWORD]}"
    case "${COMP_WORDS[1]}" in
        connect|edit|remove)
            [ "$COMP_CWORD" -eq 2 ] && _easy_ssh_complete_project "$current"
            ;;
        session)
            case "${COMP_WORDS[2]}" in
                list|new|open)
                    [ "$COMP_CWORD" -eq 3 ] && _easy_ssh_complete_project "$current"
                    ;;
            esac
            ;;
    esac
}
complete -F _easy_ssh easy-ssh
"#;

const ZSH_SHELL_HOOK: &str = r#"# >>> easy-ssh shell hook >>>
ssh() {
    if [ "$#" -eq 1 ] && command easy-ssh __is-project -- "$1"; then
        command easy-ssh connect -- "$1"
    else
        command ssh "$@"
    fi
}
# <<< easy-ssh shell hook <<<

_easy_ssh() {
    local -a projects
    projects=("${(@f)$(command easy-ssh __complete-projects)}")
    case "$words[2]" in
        connect|edit|remove)
            (( CURRENT == 3 )) && _describe -t projects 'saved project' projects
            ;;
        session)
            case "$words[3]" in
                list|new|open)
                    (( CURRENT == 4 )) && _describe -t projects 'saved project' projects
                    ;;
            esac
            ;;
    esac
}
compdef _easy_ssh easy-ssh
"#;

pub fn remote_command(remote_path: &str, agent: Agent) -> String {
    let _ = agent;
    let target = remote_path_target(remote_path);
    format!(
        "if cd -- {target} 2>/dev/null; then :; else echo 'easy-ssh: remote folder unavailable; starting in home' >&2; cd; fi; exec \"${{SHELL:-/bin/sh}}\" -l"
    )
}

fn remote_path_target(remote_path: &str) -> String {
    if remote_path == "~" {
        "\"$HOME\"".to_owned()
    } else if let Some(rest) = remote_path.strip_prefix("~/") {
        format!("\"$HOME\"/{}", shell_quote(rest))
    } else {
        shell_quote(remote_path)
    }
}

pub fn connect_args(project: &Project, agent: Agent) -> Vec<String> {
    vec![
        "-t".into(),
        "--".into(),
        project.ssh_target().into(),
        remote_command(&project.remote_path, agent),
    ]
}

pub fn connect(project: &Project, agent: Agent) -> Result<()> {
    let args = connect_args(project, agent);
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt;
        let error = Command::new("ssh").args(&args).exec();
        Err(error).context("failed to execute ssh")
    }
    #[cfg(not(unix))]
    {
        let status = Command::new("ssh").args(&args).status()?;
        if status.success() {
            Ok(())
        } else {
            bail!("ssh exited with {status}")
        }
    }
}

pub fn ghostty_args(project: &Project, agent: Agent) -> Vec<String> {
    vec![
        "-e".into(),
        "ssh".into(),
        "-tt".into(),
        project.ssh_target().into(),
        remote_command(&project.remote_path, agent),
    ]
}

pub fn connect_with_terminal(
    project: &Project,
    terminal: TerminalMode,
    agent: Agent,
) -> Result<()> {
    match terminal {
        TerminalMode::Current => connect(project, agent),
        TerminalMode::Ghostty => {
            let status = Command::new("ghostty")
                .args(ghostty_args(project, agent))
                .status()
                .context("failed to launch Ghostty; install Ghostty or use --terminal current")?;
            if status.success() {
                Ok(())
            } else {
                anyhow::bail!("Ghostty exited with {status}")
            }
        }
    }
}

pub fn tmux_workspace(project: &Project) -> String {
    let mut name = project
        .name
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character
            } else {
                '-'
            }
        })
        .collect::<String>();
    name.truncate(36);
    format!("easy-ssh-{name}")
}

fn tmux_required() -> &'static str {
    "command -v tmux >/dev/null 2>&1 || { echo 'easy-ssh: tmux is required for persistent agent sessions. Install it on this host and try again.' >&2; exit 127; };"
}

pub fn tmux_attach_command(project: &Project) -> String {
    let workspace = shell_quote(&tmux_workspace(project));
    format!(
        "{} tmux new-session -Ad -s {workspace} -c {path}; exec tmux attach-session -t {workspace}",
        tmux_required(),
        path = remote_path_target(&project.remote_path)
    )
}

pub fn session_attach_command(_project: &Project, session: &SessionRecord) -> String {
    let workspace = shell_quote(&session.workspace);
    let window = shell_quote(&format!("{}:{}", session.workspace, session.window));
    format!(
        "{} tmux has-session -t {workspace} 2>/dev/null || {{ echo 'easy-ssh: session is not active; create or resume it from the session picker.' >&2; exit 1; }}; tmux select-window -t {window}; exec tmux attach-session -t {workspace}",
        tmux_required()
    )
}

pub fn connect_session(
    project: &Project,
    session: &SessionRecord,
    terminal: TerminalMode,
) -> Result<()> {
    connect_custom_command(project, terminal, session_attach_command(project, session))
}

pub fn connect_workspace(project: &Project, terminal: TerminalMode) -> Result<()> {
    connect_custom_command(project, terminal, tmux_attach_command(project))
}

fn connect_custom_command(
    project: &Project,
    terminal: TerminalMode,
    command: String,
) -> Result<()> {
    let args = vec![
        "-e".into(),
        "ssh".into(),
        "-tt".into(),
        project.ssh_target().into(),
        command,
    ];
    match terminal {
        TerminalMode::Current => {
            let status = Command::new("ssh")
                .args(["-tt", "--", project.ssh_target(), &args[4]])
                .status()?;
            if status.success() {
                Ok(())
            } else {
                bail!("ssh exited with {status}")
            }
        }
        TerminalMode::Ghostty => {
            let status = Command::new("ghostty")
                .args(args)
                .status()
                .context("failed to launch Ghostty")?;
            if status.success() {
                Ok(())
            } else {
                bail!("Ghostty exited with {status}")
            }
        }
    }
}

pub fn create_agent_session(
    project: &Project,
    agent: Agent,
    id: &str,
    label: &str,
) -> Result<SessionRecord> {
    let label = label.trim();
    if label.is_empty() || label.contains(['\n', '\r']) {
        anyhow::bail!("session name cannot be empty or contain a newline");
    }
    let workspace = tmux_workspace(project);
    let window = format!(
        "{}-{}",
        agent.label().to_ascii_lowercase(),
        id.split('-').next().unwrap_or(id)
    );
    let agent_command = match agent {
        Agent::Shell => {
            anyhow::bail!("persistent sessions require --agent claude or --agent codex")
        }
        Agent::Claude => format!(
            "exec claude --session-id {} --name {}",
            shell_quote(id),
            shell_quote(label)
        ),
        Agent::Codex => "exec codex".into(),
    };
    let login = format!(
        "login_shell=$(getent passwd \"$(id -un)\" | cut -d: -f7); exec \"${{login_shell:-/bin/sh}}\" -lic {}",
        shell_quote(&agent_command)
    );
    let remote = format!(
        "{} tmux new-session -Ad -s {workspace} -c {path}; tmux new-window -d -t {workspace}: -n {window} -c {path} {login}; tmux select-window -t {workspace}:{window}",
        tmux_required(),
        workspace = shell_quote(&workspace),
        window = shell_quote(&window),
        path = remote_path_target(&project.remote_path),
        login = shell_quote(&login)
    );
    let status = Command::new("ssh")
        .args(["--", project.ssh_target(), &remote])
        .status()
        .context("failed to create remote agent session")?;
    if !status.success() {
        bail!("remote tmux setup exited with {status}");
    }
    Ok(SessionRecord {
        project: project.name.clone(),
        agent,
        id: id.into(),
        label: label.into(),
        workspace,
        window,
        color: "cyan".into(),
    })
}

pub fn resume_agent_session(project: &Project, session: &SessionRecord) -> Result<()> {
    let agent_command = match session.agent {
        Agent::Shell => anyhow::bail!("saved Shell sessions cannot be resumed"),
        Agent::Claude => format!("exec claude --resume {}", shell_quote(&session.id)),
        Agent::Codex => "exec codex resume".into(),
    };
    let login = format!(
        "login_shell=$(getent passwd \"$(id -un)\" | cut -d: -f7); exec \"${{login_shell:-/bin/sh}}\" -lic {}",
        shell_quote(&agent_command)
    );
    let remote = format!(
        "{} tmux new-session -Ad -s {workspace} -c {path}; tmux new-window -d -t {workspace}: -n {window} -c {path} {login}; tmux select-window -t {workspace}:{window}",
        tmux_required(),
        workspace = shell_quote(&session.workspace),
        window = shell_quote(&session.window),
        path = remote_path_target(&project.remote_path),
        login = shell_quote(&login)
    );
    let status = Command::new("ssh")
        .args(["--", project.ssh_target(), &remote])
        .status()?;
    if status.success() {
        Ok(())
    } else {
        bail!("remote agent resume setup exited with {status}")
    }
}

pub fn active_session_windows(project: &Project) -> Result<BTreeSet<String>> {
    let workspace = tmux_workspace(project);
    let remote = format!(
        "command -v tmux >/dev/null 2>&1 && tmux list-windows -t {} -F '#{{window_name}}' 2>/dev/null || true",
        shell_quote(&workspace)
    );
    let output = Command::new("ssh")
        .args(["--", project.ssh_target(), &remote])
        .output()?;
    Ok(String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::to_owned)
        .collect())
}

pub fn set_session_color(project: &Project, session: &SessionRecord, color: &str) -> Result<()> {
    let remote = format!(
        "tmux set-window-option -t {window} @easy_ssh_color {color} 2>/dev/null || true; tmux set-option -t {workspace} window-status-format '#[fg=#{{@easy_ssh_color}}]#W#[default]' 2>/dev/null || true",
        window = shell_quote(&format!("{}:{}", session.workspace, session.window)),
        workspace = shell_quote(&session.workspace),
        color = shell_quote(color),
    );
    let status = Command::new("ssh")
        .args(["--", project.ssh_target(), &remote])
        .status()?;
    if status.success() {
        Ok(())
    } else {
        bail!("failed to update remote tmux session color")
    }
}

pub fn discover_aliases(paths: &AppPaths) -> Vec<String> {
    let mut visited = BTreeSet::new();
    let mut aliases = BTreeSet::new();
    scan_config(&paths.ssh_config, &paths.home, &mut visited, &mut aliases);
    aliases.into_iter().collect()
}

fn scan_config(
    path: &Path,
    home: &Path,
    visited: &mut BTreeSet<PathBuf>,
    aliases: &mut BTreeSet<String>,
) {
    let path = path.to_path_buf();
    if !visited.insert(path.clone()) {
        return;
    }
    let Ok(contents) = fs::read_to_string(&path) else {
        return;
    };
    let base = path
        .parent()
        .unwrap_or(home.join(".ssh").as_path())
        .to_path_buf();
    for raw in contents.lines() {
        let line = raw.split('#').next().unwrap_or("").trim();
        let mut parts = line.split_whitespace();
        let Some(keyword) = parts.next() else {
            continue;
        };
        if keyword.eq_ignore_ascii_case("host") {
            for alias in parts {
                if !alias.starts_with('!')
                    && !alias
                        .bytes()
                        .any(|byte| matches!(byte, b'*' | b'?' | b'[' | b']'))
                {
                    aliases.insert(alias.to_owned());
                }
            }
        } else if keyword.eq_ignore_ascii_case("include") {
            for pattern in parts {
                let pattern = expand_path(pattern.trim_matches('"'), &base, home);
                if let Some(pattern) = pattern.to_str()
                    && let Ok(matches) = glob(pattern)
                {
                    for included in matches.flatten() {
                        scan_config(&included, home, visited, aliases);
                    }
                }
            }
        }
    }
}

fn expand_path(value: &str, base: &Path, home: &Path) -> PathBuf {
    if value == "~" {
        home.to_path_buf()
    } else if let Some(rest) = value.strip_prefix("~/") {
        home.join(rest)
    } else {
        let path = PathBuf::from(value);
        if path.is_absolute() {
            path
        } else {
            base.join(path)
        }
    }
}

pub fn doctor(paths: &AppPaths, file: &ProjectFile, shells: &[Shell]) -> Vec<(bool, String)> {
    let mut checks = Vec::new();
    checks.push((
        paths.registry.exists(),
        format!("project registry: {}", paths.registry.display()),
    ));
    checks.push((
        read_or_empty(&paths.ssh_config)
            .map(|value| value.lines().any(|line| line.trim() == INCLUDE_LINE))
            .unwrap_or(false),
        format!("SSH include installed: {}", paths.ssh_config.display()),
    ));
    checks.push((
        paths.managed_ssh_config.exists(),
        format!("managed SSH config: {}", paths.managed_ssh_config.display()),
    ));
    if paths.managed_ssh_config.exists() {
        let syntax_target = file
            .projects
            .iter()
            .find(|project| matches!(project.connection, Connection::NewHost { .. }))
            .map(|project| project.name.as_str())
            .unwrap_or("easy-ssh-doctor");
        let syntax_ok = Command::new("ssh")
            .args([
                "-G",
                "-F",
                &paths.managed_ssh_config.to_string_lossy(),
                "--",
                syntax_target,
            ])
            .output()
            .map(|output| output.status.success())
            .unwrap_or(false);
        checks.push((syntax_ok, "managed SSH config syntax".into()));
    }
    for shell in shells {
        let startup_file = shell.startup_file(paths);
        checks.push((
            read_or_empty(startup_file)
                .map(|value| value.contains(HOOK_START) && value.contains(HOOK_END))
                .unwrap_or(false),
            format!("{shell:?} hook installed: {}", startup_file.display()),
        ));
    }
    for project in &file.projects {
        checks.push((
            project.validate().is_ok(),
            format!("project {} is valid", project.name),
        ));
    }
    let aliases = discover_aliases(paths);
    for project in &file.projects {
        if let Connection::ExistingAlias { ssh_alias } = &project.connection {
            checks.push((
                aliases.iter().any(|alias| alias == ssh_alias),
                format!("SSH alias {ssh_alias} is declared"),
            ));
        }
    }
    checks
}

fn quote_config(value: &str) -> String {
    if value.bytes().all(|byte| {
        byte.is_ascii_alphanumeric()
            || matches!(byte, b'.' | b'/' | b'_' | b'-' | b'~' | b':' | b'@')
    }) {
        value.to_owned()
    } else {
        format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

fn read_or_empty(path: &Path) -> Result<String> {
    match fs::read_to_string(path) {
        Ok(value) => Ok(value),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
        Err(error) => Err(error).with_context(|| format!("failed to read {}", path.display())),
    }
}

fn backup_once(path: &Path) -> Result<()> {
    if !path.exists() {
        return Ok(());
    }
    let backup = PathBuf::from(format!("{}.easy-ssh.bak", path.display()));
    if !backup.exists() {
        fs::copy(path, &backup).with_context(|| {
            format!(
                "failed to back up {} to {}",
                path.display(),
                backup.display()
            )
        })?;
    }
    Ok(())
}

